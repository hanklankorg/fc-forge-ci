// The Cargo witness changes the release fixture in six lines and nothing else,
// and what it changes them to is a workflow that builds with build-cargo in
// the image, before the hand-off, behind the same gate.
func TestReleaseWorkflowForCargo(t *testing.T) {
	t.Parallel()

	const image = "registry.example/rust@sha256:1111111111111111111111111111111111111111111111111111111111111111"

	cargo, err := releaseWorkflowForCargo(layerMinimalReleaseFixture, image)
	if err != nil {
		t.Fatal(err)
	}

	removed, added := lineDifference(layerMinimalReleaseFixture, cargo), lineDifference(cargo, layerMinimalReleaseFixture)

	wantRemoved := []string{
		"            --changelog-only",
		"            --tag \"${RELEASE_TAG}\" --expected-parent \"${REQUEST_SHA}\" \\",
		"          main-package: ./cmd/layer-release-canary",
		"        uses: https://FORGE_HOST/OWNER/forge-ci/.forgejo/actions/build-go@PIN_FORGE_CI_SHA",
		"      - name: Validate the prepared changelog-only commit",
		"      image: " + goModuleConsumerImage,
	}
	wantAdded := []string{
		"            --tag \"${RELEASE_TAG}\" --expected-parent \"${REQUEST_SHA}\"",
		"        uses: https://FORGE_HOST/OWNER/forge-ci/.forgejo/actions/build-cargo@PIN_FORGE_CI_SHA",
		"      - name: Validate the prepared release commit",
		"      image: " + image,
		"      runtime-image-rust: " + image,
	}

	if !slices.Equal(removed, wantRemoved) || !slices.Equal(added, wantAdded) {
		t.Fatalf("the Cargo release removes %q and adds %q, want %q and %q", removed, added, wantRemoved, wantAdded)
	}

	// The layer's renderer writes the workflow out again when it adds an
	// administrator's input, so the lines must survive that too.
	var document yaml.Node
	if err := yaml.Unmarshal([]byte(layerMinimalReleaseFixture), &document); err != nil {
		t.Fatal(err)
	}

	var rewritten bytes.Buffer

	encoder := yaml.NewEncoder(&rewritten)
	encoder.SetIndent(2)

	if err := encoder.Encode(&document); err != nil {
		t.Fatal(err)
	}

	again, err := releaseWorkflowForCargo(rewritten.String(), image)
	if err != nil {
		t.Fatalf("the fixture as the renderer rewrites it: %v", err)
	}

	for name, workflow := range map[string]string{"as committed": cargo, "as rewritten": again} {
		if finding := cargoWorkflowFinding(workflow, image); finding != "" {
			t.Errorf("%s: %s", name, finding)
		}
	}

	if finding := cargoWorkflowFinding(layerMinimalReleaseFixture, image); finding == "" {
		t.Error("the Go release passes for a Cargo one")
	}

	// A fixture that is already a Cargo release, or no longer has a line the
	// witness changes, must stop it instead of releasing something else.
	for name, fixture := range map[string]string{
		"already changed":   cargo,
		"another image":     strings.ReplaceAll(layerMinimalReleaseFixture, goModuleConsumerImage, "docker.io/library/golang:1"),
		"another build":     strings.ReplaceAll(layerMinimalReleaseFixture, "/build-go@", "/build-other@"),
		"no check to relax": strings.ReplaceAll(layerMinimalReleaseFixture, "--changelog-only", "--request-is-release"),
	} {
		if _, err := releaseWorkflowForCargo(fixture, image); err == nil {
			t.Errorf("%s: the fixture was accepted", name)
		}
	}
}

// lineDifference returns the lines of text that other does not hold, sorted.
func lineDifference(text, other string) []string {
	held := map[string]int{}
	for line := range strings.SplitSeq(other, "\n") {
		held[line]++
	}

	var only []string

	for line := range strings.SplitSeq(text, "\n") {
		if held[line] == 0 {
			only = append(only, line)

			continue
		}

		held[line]--
	}

	slices.Sort(only)

	return only
}

// cargoWorkflowFinding reads a release workflow as Forgejo would and says what
// keeps it from being the Cargo witness's, or "".
func cargoWorkflowFinding(text, image string) string {
	var workflow struct {
		Jobs map[string]struct {
			With      map[string]string `yaml:"with"`
			Container struct {
				Image string `yaml:"image"`
			} `yaml:"container"`
			Steps []struct {
				Uses string            `yaml:"uses"`
				Run  string            `yaml:"run"`
				With map[string]string `yaml:"with"`
			} `yaml:"steps"`
		} `yaml:"jobs"`
	}
	if err := yaml.Unmarshal([]byte(text), &workflow); err != nil {
		return err.Error()
	}

	build := workflow.Jobs["build"]
	if workflow.Jobs["prepare"].With["runtime-image-rust"] != image || build.Container.Image != image {
		return fmt.Sprintf("the version job runs in %q and the build in %q, want both in %s",
			workflow.Jobs["prepare"].With["runtime-image-rust"], build.Container.Image, image)
	}

	validated, built, uploaded := -1, -1, -1

	for index, step := range build.Steps {
		switch {
		case strings.Contains(step.Run, "forge-ci release validate-tag"):
			if strings.Contains(step.Run, "--changelog-only") || !strings.HasSuffix(strings.TrimSpace(step.Run), `--expected-parent "${REQUEST_SHA}"`) {
				return "the build's check of the prepared commit is " + step.Run
			}

			validated = index
		case strings.Contains(step.Uses, "/.forgejo/actions/build-go@"):
			return "the build still calls build-go"
		case strings.Contains(step.Uses, "/.forgejo/actions/build-cargo@"):
			want := map[string]string{
				"version": "${{ needs.prepare.outputs.release-tag }}", "commit": "${{ needs.prepare.outputs.release-sha }}", "enable-build-sbom": "false",
			}
			if built != -1 || len(step.With) != len(want) {
				return fmt.Sprintf("build-cargo is called with %v, want once with %v", step.With, want)
			}

			for input, value := range want {
				if step.With[input] != value {
					return fmt.Sprintf("build-cargo is called with %v, want %v", step.With, want)
				}
			}

			built = index
		case strings.Contains(step.Uses, "/.forgejo/actions/upload-dist@"):
			uploaded = index
		}
	}

	if validated == -1 || built <= validated || uploaded <= built {
		return fmt.Sprintf("the prepared commit is checked at step %d, built at %d and handed over at %d, want that order", validated, built, uploaded)
	}

	return ""
}

func TestShapeCargoCanary(t *testing.T) {
	t.Parallel()

	const image = "registry.example/rust@sha256:1111111111111111111111111111111111111111111111111111111111111111"

	minimal := func() map[string]string {
		return map[string]string{
			"go.mod": "module example.invalid/layer-release-canary\n", releaseGoCanaryMain: "package main\n",
			"CHANGELOG.md": "# Changelog\n", releaseWorkflowFile: layerMinimalReleaseFixture,
		}
	}

	files := minimal()
	if err := shapeCargoCanary(files, image); err != nil {
		t.Fatal(err)
	}

	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}

	slices.Sort(names)

	if want := []string{layerDeclarationFile, releaseWorkflowFile, "CHANGELOG.md", "Cargo.lock", "Cargo.toml", "src/main.rs"}; !slices.Equal(names, want) {
		t.Errorf("the Cargo canary's files are %v, want %v", names, want)
	}

	if finding := cargoWorkflowFinding(files[releaseWorkflowFile], image); finding != "" || files["CHANGELOG.md"] != "# Changelog\n" {
		t.Errorf("the Cargo canary's workflow: %s; its changelog: %q", finding, files["CHANGELOG.md"])
	}

	for name, change := range map[string]func(files map[string]string){
		"no Go module":      func(files map[string]string) { delete(files, "go.mod") },
		"no Go command":     func(files map[string]string) { delete(files, releaseGoCanaryMain) },
		"another workflow":  func(files map[string]string) { files[releaseWorkflowFile] = "jobs: {}\n" },
		"no workflow there": func(files map[string]string) { delete(files, releaseWorkflowFile) },
	} {
		files := minimal()
		change(files)

		if err := shapeCargoCanary(files, image); err == nil {
			t.Errorf("%s: the files were accepted", name)
		}
	}
}

// The crate is consistent as it is requested, and the product's own bump of
// its manifest gives the release the witness then looks for.
func TestCargoCanaryCrate(t *testing.T) {
	t.Parallel()

	if findings := cargoVersionFindings(cargoCanaryManifest, cargoCanaryLock, cargoCanaryCrate, "0.0.0"); len(findings) != 0 {
		t.Errorf("the requested crate: %v", findings)
	}

	bumped, section, err := domainversion.UpdateCargoVersion(cargoCanaryManifest, "0.0.1")
	if err != nil || section != domainversion.CargoSectionPackage {
		t.Fatalf("the product does not bump the canary's own package version: section %d, %v", section, err)
	}

	lock := strings.Replace(cargoCanaryLock, `version = "0.0.0"`, `version = "0.0.1"`, 1)
	if findings := cargoVersionFindings(bumped, lock, cargoCanaryCrate, "0.0.1"); len(findings) != 0 {
		t.Errorf("the bumped crate: %v", findings)
	}

	if strings.Contains(cargoCanaryManifest, "dependencies") || strings.Count(cargoCanaryLock, "[[package]]") != 1 {
		t.Error("the canary has a dependency, and its release must need no registry")
	}

	if !strings.Contains(cargoCanaryMain, `concat!("`+cargoCanaryCrate+` ", env!("CARGO_PKG_VERSION"))`) {
		t.Error("the canary no longer compiles its manifest's version into the line the release is held to")
	}
}

func TestCargoVersionFindings(t *testing.T) {
	t.Parallel()

	const (
		manifest = "[package]\nname = \"app\"\nversion = \"0.0.1\"\n"
		lock     = "version = 4\n\n[[package]]\nname = \"app\"\nversion = \"0.0.1\"\n\n[[package]]\nname = \"dep\"\nversion = \"0.0.0\"\n"
	)

	for name, test := range map[string]struct {
		manifest, lock string
		findings       int
	}{
		"both at the release":         {manifest: manifest, lock: lock},
		"a stale manifest":            {manifest: strings.Replace(manifest, "0.0.1", "0.0.0", 1), lock: lock, findings: 1},
		"a stale lockfile":            {manifest: manifest, lock: strings.Replace(lock, "0.0.1", "0.0.0", 1), findings: 1},
		"both stale":                  {manifest: strings.Replace(manifest, "0.0.1", "0.0.0", 1), lock: strings.Replace(lock, "0.0.1", "0.0.0", 1), findings: 2},
		"another crate":               {manifest: strings.Replace(manifest, "app", "other", 1), lock: lock, findings: 1},
		"a lockfile without it":       {manifest: manifest, lock: "version = 4\n\n[[package]]\nname = \"dep\"\nversion = \"0.0.1\"\n", findings: 1},
		"listed twice":                {manifest: manifest, lock: lock + "\n[[package]]\nname = \"app\"\nversion = \"0.0.1\"\n", findings: 1},
		"a version in a comment only": {manifest: "[package]\nname = \"app\"\n# version = \"0.0.1\"\nversion = \"0.0.10\"\n", lock: lock, findings: 1},
		"not TOML":                    {manifest: "[package", lock: "[[package", findings: 2},
	} {
		if findings := cargoVersionFindings(test.manifest, test.lock, "app", "0.0.1"); len(findings) != test.findings {
			t.Errorf("%s: findings are %v, want %d", name, findings, test.findings)
		}
	}
}

func TestArchivedFile(t *testing.T) {
	t.Parallel()

	var packed bytes.Buffer

	zipped := gzip.NewWriter(&packed)
	writer := tar.NewWriter(zipped)

	for _, file := range []struct {
		name, content string
		kind          byte
	}{
		{"canary/", "", tar.TypeDir},
		{"canary/link", "", tar.TypeSymlink},
		{"canary/binary", "\x7fELF layer-release-canary 0.0.1\n", tar.TypeReg},
	} {
		if err := writer.WriteHeader(&tar.Header{Name: file.name, Typeflag: file.kind, Mode: 0o755, Size: int64(len(file.content)), Linkname: "binary"}); err != nil {
			t.Fatal(err)
		}

		if _, err := writer.Write([]byte(file.content)); err != nil {
			t.Fatal(err)
		}
	}

	if err := errors.Join(writer.Close(), zipped.Close()); err != nil {
		t.Fatal(err)
	}

	content, err := archivedFile(packed.Bytes(), "canary/binary", 1<<10)
	if err != nil || !bytes.Contains(content, []byte("layer-release-canary 0.0.1")) {
		t.Errorf("the archived binary is %q (%v)", content, err)
	}

	for name, test := range map[string]struct {
		archive []byte
		file    string
		limit   int64
	}{
		"absent":         {packed.Bytes(), "canary/other", 1 << 10},
		"a link":         {packed.Bytes(), "canary/link", 1 << 10},
		"over the limit": {packed.Bytes(), "canary/binary", 4},
		"not an archive": {[]byte("plain"), "canary/binary", 1 << 10},
	} {
		if content, err := archivedFile(test.archive, test.file, test.limit); err == nil {
			t.Errorf("%s: read %q", name, content)
		}
	}
}
